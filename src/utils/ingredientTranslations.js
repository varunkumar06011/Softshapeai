// Pre-build a lowercase key map for case-insensitive lookup
const _lowerKeyMap = {};
for (const key of Object.keys(INGREDIENT_TRANSLATIONS)) {
  _lowerKeyMap[key.toLowerCase().trim()] = key;
}

export function translateIngredientName(name, lang) {
  if (!name || lang === 'en') return name;
  const trimmed = name.trim();
  const lowerKey = trimmed.toLowerCase();
  const exactKey = _lowerKeyMap[lowerKey];
  if (exactKey) {
    const entry = INGREDIENT_TRANSLATIONS[exactKey];
    if (entry && entry[lang]) return entry[lang];
  }
  return name;
}

